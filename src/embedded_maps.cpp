const char* embedded_map(const char* id) {
    if (!id) return nullptr;
    if (std::strcmp(id, "cave") == 0) return k_cave;
    if (std::strcmp(id, "forest") == 0) return k_forest;
    if (std::strcmp(id, "ruins") == 0) return k_ruins;
    if (std::strcmp(id, "sanctum") == 0) return k_sanctum;
    if (std::strcmp(id, "village") == 0) return k_village;
    return nullptr;
}
