#pragma once
#include "png.h"
#include "../types.h"

#include <string>
#include <vector>

// Тайлы: файлы графики, раскладка слотов и вид по умолчанию.
//
// Про SDL здесь ничего нет намеренно — так это проверяется тестами без окна,
// как жесты и ходьба. Всё, что требует видеокарты, лежит в tileset.h.
//
// Основной способ хранения — по картинке на тайл: data/tiles/wall.png,
// grass.png и так далее. Редактор True Joint Tile Maker открывает и сохраняет
// ровно такие файлы, поэтому между «нарисовал» и «увидел в игре» нет ни
// одного преобразования. Заодно у одного тайла нет и потолка в 63 пикселя:
// редактор не берёт картинки больше 512 по стороне, и это весь предел.
//
// Второй способ — лист 8x8 в одном файле: он был у редактора раньше, а теперь
// остаётся как способ увезти весь набор одним файлом. Отдельные файлы важнее:
// если тайл есть и там, и там, берётся отдельный файл.

namespace gfx {

const int TJTM_COLS  = 8;
const int TJTM_ROWS  = 8;
const int TJTM_SLOTS = TJTM_COLS * TJTM_ROWS;

// Редактор не открывает картинки больше 512 пикселей по стороне. Для
// отдельного файла это и есть весь предел на тайл.
const int TILE_MAX_PX = 512;

// А в листе те же 512 делятся на 8 ячеек, и в ячейке на пиксель больше
// тайла — отсюда потолок листа: 63 на 63.
const int TJTM_MAX_TILE = TILE_MAX_PX / TJTM_COLS - 1;

// Размер, в котором игра рисует свой вид по умолчанию при экспорте. Ровно
// две клетки шрифта в высоту, так что экспорт совпадает с тем, что видно
// на экране телефона.
const int TILE_PX = 32;

// Служебный цвет фона листа. Сравнение идёт по всем четырём каналам — так же,
// как в редакторе, поэтому прозрачный пиксель за маркер никогда не примут
// и рисовать тайлы с прозрачностью безопасно.
bool tjtm_is_marker(const unsigned char* rgba);

// Разрезать лист на 64 тайла по правилам редактора. Пустая ячейка даёт
// пустую картинку — это не ошибка, а «слот не нарисован».
bool tjtm_slice(const Image& sheet, std::vector<Image>* out, std::string* err);

// Собрать 64 тайла обратно в лист. Тайлы могут быть разного размера:
// ячейка берётся по самому большому, как и в редакторе.
bool tjtm_compose(const std::vector<Image>& tiles, Image* out, std::string* err);

// --- раскладка слотов ---
//
// Ряд 0 — местность, ряды 1 и 2 — объекты, остальные свободны: рисуйте в них
// что угодно, игра туда не смотрит. Номер слота — это строка * 8 + столбец,
// то же самое, что в редакторе.
// Имя не просто «Slot»: так в игре называются ячейки снаряжения.
enum TileSlot {
    SLOT_FLOOR = 0, SLOT_WALL, SLOT_WATER, SLOT_TREE,
    SLOT_GRASS, SLOT_ROAD, SLOT_DEADWATER,

    SLOT_PLAYER = 8, SLOT_NPC, SLOT_MOB, SLOT_EXIT,
    SLOT_SIGN, SLOT_ITEM, SLOT_BED, SLOT_CHEST,

    SLOT_PORTAL = 16, SLOT_NOTE
};

// -1, если для этого нет своего слота.
int slot_of_tile(Tile t);
int slot_of_glyph(unsigned cp);
// Человеческое имя слота — для документации и сообщений об ошибках.
const char* slot_name(int slot);
// Имя файла слота без расширения: "wall", "grass"... Ноль у свободных слотов —
// у них нет имени, потому что игра в них не смотрит.
const char* slot_file(int slot);

// --- графика по файлам ---

// Читает <dir>/<имя слота>.png во все слоты, для которых файл нашёлся.
// Возвращает, сколько прочитано. Отсутствие файла — не ошибка; файл, который
// есть, но не читается, кладёт причину в err и слот оставляет пустым.
int load_slot_files(const std::string& dir, std::vector<Image>* tiles, std::string* err);

// Пишет вид по умолчанию по картинке на слот. Каталог создаётся.
bool save_slot_files(const std::string& dir, int size, std::string* err);

// --- вид по умолчанию ---
//
// Те же цвета и знаки, которыми карта рисуется без листа тайлов. Отсюда их
// берёт и отрисовка, и экспорт: иначе нарисованное на экране и сохранённое
// в файл рано или поздно разошлись бы.
struct Rgba { unsigned char r, g, b, a; };

// Подложка под героем: полупрозрачное пятно, по которому его видно на любой
// местности. Она входит в сам тайл героя, а не рисуется поверх — иначе
// нарисованный герой получал бы жёлтый квадрат под ноги, а экспорт возвращал
// бы не тот кадр, из которого сделан.
Rgba default_player_backing();

Rgba default_tile_color(Tile t);
unsigned default_tile_texture(Tile t);      // 0 — поверх заливки ничего нет
Rgba default_object_color(unsigned cp);

// Нарисовать вид по умолчанию для одного слота в картинку size x size.
// Пустая картинка означает, что у слота своего вида нет.
Image default_slot_art(int slot, int size);

// Собрать весь лист с видом по умолчанию: то, с чего удобно начинать рисовать.
Image default_sheet(int size);

} // namespace gfx
