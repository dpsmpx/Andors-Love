#pragma once
#include "../game.h"

// Ходьба к точке: герой идёт к указанной клетке, пока не упрётся или пока
// цель не сменят. Поиска пути здесь нет намеренно — тот же жадный шаг, что
// у мобов: сперва по оси с большей разницей, потом по другой. Игрок видит
// ровно то, что обещано: «идёт в сторону точки, пока может».
//
// Темп задаётся временем, а не кадрами: между шагами проходит фиксированное
// число миллисекунд, и на быстром телефоне герой идёт ровно так же, как на
// медленном. За один вызов делается не больше одного шага — даже если кадр
// подвис на секунду, герой не проскочит полкарты рывком.

namespace gfx {

// Что прервало ходьбу: пригодится, чтобы решить, показывать ли что-то игроку.
enum WalkStop {
    WS_RUNNING = 0,   // ещё идёт
    WS_ARRIVED,       // дошёл
    WS_BLOCKED,       // упёрся
    WS_EVENT          // наступил на что-то: переход, сундук, NPC, бой
};

class Walker {
public:
    Walker();

    // Задать цель. Бег отличается только скоростью шага. Часы шагов при
    // этом не сбрасываются: смена цели не даёт лишнего шага, но если ходьба
    // стояла дольше паузы, первый шаг делается сразу.
    void go(Vec2 target, bool run);
    void stop();

    bool active() const { return active_; }
    bool running() const { return run_; }
    Vec2 target() const { return target_; }
    WalkStop last_stop() const { return stop_; }
    // Чем кончился последний шаг и куда он был сделан: по этому оболочка
    // решает, заводить ли разговор или показывать табличку — ходьба должна
    // приводить туда же, куда приводит шаг вручную.
    Bump last_bump() const { return bump_; }
    int  last_dx() const { return last_dx_; }
    int  last_dy() const { return last_dy_; }

    // Держать цель у пальца: ведение цели не сбивает темп шагов, иначе
    // мелкое дрожание руки заставляло бы героя топтаться быстрее обычного.
    void retarget(Vec2 target, bool run);

    // Один шаг, если пришло время. now_ms — часы кадра. Возвращает true,
    // если герой действительно сдвинулся (значит, миру пора сделать ход).
    bool update(Game& g, unsigned now_ms);

    // Интервал между шагами, мс. Подобран под палец на экране телефона:
    // шагом — примерно четыре клетки в секунду, бегом — семь.
    static unsigned step_ms(bool run) { return run ? WALK_RUN_MS : WALK_STEP_MS; }

    static const unsigned WALK_STEP_MS = 260;
    static const unsigned WALK_RUN_MS  = 145;

private:
    bool try_axis(Game& g, int dx, int dy, Bump* out);

    bool     active_;
    bool     run_;
    Bump     bump_;
    int      last_dx_, last_dy_;
    Vec2     target_;
    unsigned next_ms_;
    WalkStop stop_;
};

// Прерывает ли этот исход шага ходьбу. Подбор с земли — не прерывает:
// идти через траву, собирая её, естественно. Всё, что открывает экран
// или начинает бой, ходьбу останавливает.
bool walk_interrupted_by(Bump b);

} // namespace gfx
