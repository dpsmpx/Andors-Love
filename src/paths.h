#pragma once
#include <string>

// Где лежат карты и куда писать сохранения. Обе оболочки — терминальная и
// графическая — обязаны отвечать на это одинаково: иначе игрок сохранится
// в одной и не найдёт сохранения в другой.

namespace paths {

// Каталог годится, только если в него удаётся создать и записать файл.
bool dir_writable(const std::string& dir);

// Каталог сохранений: $ANDORS_LOVE_SAVE, затем saves/ в рабочем каталоге,
// затем $HOME/.andors-love, затем saves/ рядом с бинарником, затем $TMPDIR.
// Внутри APK рабочий каталог может быть недоступен для записи, и молча
// терять прогресс нельзя.
std::string save_dir(const char* argv0);

// Каталог карт: $ANDORS_LOVE_DATA, рабочий каталог, рядом с бинарником.
// Если ничего не нашлось, возвращается привычный путь — чтобы текст ошибки
// был понятным; сами карты при этом всё равно есть вшитые в бинарник.
std::string data_root(const char* argv0);

// Существует ли файл и читается ли он.
bool file_exists(const std::string& path);

// Каталог графики: $ANDORS_LOVE_TILES, data/tiles в рабочем каталоге, то же
// рядом с бинарником, наконец tiles рядом с ним. Там лежат картинки по одной
// на тайл — wall.png, grass.png и так далее, — и там же может лежать лист
// tiles.png, если набор возят одним файлом.
//
// Каталога может не быть, и это не ошибка: без него игра рисует карту
// заливкой и знаками шрифта, как делала до всякой графики.
std::string tiles_dir(const char* argv0);

} // namespace paths
